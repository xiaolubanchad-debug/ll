export function pinyinUsername() {
  let name: string;
  do {
    name =
      surnames[randomInt(surnames.length)] +
      first[randomInt(first.length)] +
      last[randomInt(last.length)];
  } while (name.length < 6 || name.length > 10);
  return name;
}
